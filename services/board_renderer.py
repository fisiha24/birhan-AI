def build_scene_render_layout(draw, scene, duration):

    scene_text = get_scene_text(scene)

    if not scene_text:
        return None

    bullet_points = split_into_bullet_points(scene_text)

    if not bullet_points:
        return None

    font_size = (
        scene.get("board_font_size", BOARD_TEXT_FONT_SIZE)
        if isinstance(scene, dict)
        else BOARD_TEXT_FONT_SIZE
    )

    body_font = load_font(font_size, bold=False)
    line_height = int(font_size * 1.45)
    bullet_gap = int(font_size * 0.65)

    max_width = BOARD_TEXT_MAX_WIDTH

    word_boundaries = scene.get("speech_word_boundaries") if isinstance(scene, dict) else None

    word_timelines = build_bullet_word_timelines(
        bullet_points=bullet_points, duration=duration, word_boundaries=word_boundaries,
    )

    return {
        "bullet_points": bullet_points,
        "body_font": body_font,
        "line_height": line_height,
        "bullet_gap": bullet_gap,
        "word_timelines": word_timelines,
        "max_width": max_width,
    }


def _fit_title_font(draw, title, max_width):

    """
    Finds the largest font size (up to TITLE_MAX_FONT_SIZE) at
    which `title` fits within max_width, so a long title can
    never be centered/drawn past the safe left/right edges of the
    board.
    """

    for size in range(TITLE_MAX_FONT_SIZE, TITLE_MIN_FONT_SIZE - 1, -2):

        font = load_font(size, bold=True)

        if get_text_width(draw, title, font) <= max_width:
            return font

    return load_font(TITLE_MIN_FONT_SIZE, bold=True)


def _draw_board_title(draw, scene, theme):

    title = get_scene_title(scene)

    if not title:
        return

    palette = PALETTES.get(theme.get("palette", "deep"), PALETTES["deep"])

    title_font = _fit_title_font(draw, title, TITLE_MAX_WIDTH)

    title_width = get_text_width(draw, title, title_font)

    # Clamp so the title can never be positioned past the safe
    # margins, even in a rounding edge case.
    title_x = max(
        TITLE_SAFE_MARGIN,
        min((VIDEO_WIDTH - title_width) // 2, VIDEO_WIDTH - TITLE_SAFE_MARGIN - title_width),
    )

    draw.text((title_x, 32), title, font=title_font, fill=palette["heading"])


def _draw_one_bullet(draw, theme, text_x, current_y, bullet_text, bullet_lines, body_font, line_height):

    bullet_color = pick_bullet_color(theme, bullet_text)

    bullet_x = text_x
    bullet_y = current_y + 6

    draw_marker(draw, bullet_x, bullet_y, 14, bullet_color, theme.get("marker", "circle"))

    text_start_x = text_x + 35

    for line_index, line in enumerate(bullet_lines):
        line_y = current_y + (line_index * line_height)
        draw.text((text_start_x, line_y), line, font=body_font, fill=bullet_color)


def _draw_bullet_block_clipped(draw, theme, text_x, current_y, bullet_text, body_font, max_width, line_height, bullet_gap):

    """
    Wraps `bullet_text`, then draws only as many of its wrapped
    lines as fully fit above BOARD_TEXT_BOTTOM_Y. This is the
    hard vertical clipping boundary: no line is ever drawn if its
    bottom edge would fall on or past BOARD_TEXT_BOTTOM_Y, so text
    can never bleed out of the board's writable area regardless of
    upstream measurement rounding. Returns the new current_y.
    """

    bullet_lines = wrap_text(draw, bullet_text, body_font, max_width - 55)

    if not bullet_lines:
        return current_y

    drawable_lines = []

    for line in bullet_lines:

        line_bottom = current_y + (len(drawable_lines) + 1) * line_height

        if line_bottom > BOARD_TEXT_BOTTOM_Y:
            break

        drawable_lines.append(line)

    if not drawable_lines:
        return current_y

    _draw_one_bullet(draw, theme, text_x, current_y, bullet_text, drawable_lines, body_font, line_height)

    return current_y + len(drawable_lines) * line_height + bullet_gap


def _draw_bullet_text(draw, scene, theme, time_position, layout):

    text_x = BOARD_TEXT_LEFT_X

    body_font = layout["body_font"]
    line_height = layout["line_height"]
    bullet_gap = layout["bullet_gap"]
    max_width = layout["max_width"]

    current_y = BOARD_TEXT_TOP_Y

    # ------------------------------------------------------
    # 1) Redraw everything already written on this board by
    #    earlier scenes - fully, statically. This is what keeps
    #    the board from ever appearing to "erase" unfinished
    #    notes just because a scene boundary passed.
    # ------------------------------------------------------

    prior_bullets = scene.get("board_prior_bullets", []) if isinstance(scene, dict) else []

    for bullet_text in prior_bullets:

        if current_y >= BOARD_TEXT_BOTTOM_Y:
            break

        current_y = _draw_bullet_block_clipped(
            draw, theme, text_x, current_y, bullet_text, body_font, max_width, line_height, bullet_gap
        )

    # ------------------------------------------------------
    # 2) Progressively reveal THIS scene's own new bullets, word
    #    by word, in sync with its narration - continuing to
    #    write below whatever step 1 already drew. Each bullet
    #    still passes through the same hard vertical clip.
    # ------------------------------------------------------

    bullet_points = layout["bullet_points"]
    word_timelines = layout["word_timelines"]

    for bullet_index, bullet_text in enumerate(bullet_points):

        if current_y >= BOARD_TEXT_BOTTOM_Y:
            break

        timeline = word_timelines[bullet_index]

        words = timeline["words"]
        word_starts = timeline["word_starts"]

        if not words:
            continue

        if not word_starts or word_starts[0] is None or time_position < word_starts[0]:
            continue

        visible_word_count = get_visible_word_count(word_starts, time_position)

        if visible_word_count <= 0:
            continue

        visible_text = " ".join(words[:visible_word_count])

        if not visible_text:
            continue

        current_y = _draw_bullet_block_clipped(
            draw, theme, text_x, current_y, visible_text, body_font, max_width, line_height, bullet_gap
        )


def _draw_footer(draw, scene):

    footer_font = load_font(18, bold=False)

    draw.text((45, 680), "Birhan AI", font=footer_font, fill=GRAY)

    scene_number = scene.get("scene_number", "")

    if scene_number:

        text = "Scene " + str(scene_number)

        width = get_text_width(draw, text, footer_font)

        draw.text((VIDEO_WIDTH - width - 45, 680), text, font=footer_font, fill=GRAY)


def _draw_progress_bar(draw, progress):

    progress = max(0.0, min(float(progress), 1.0))

    bar_x1, bar_x2 = 45, VIDEO_WIDTH - 45
    bar_y1, bar_y2 = 705, 712

    draw.rectangle([bar_x1, bar_y1, bar_x2, bar_y2], fill=(225, 225, 225))

    progress_width = int((bar_x2 - bar_x1) * progress)

    if progress_width > 0:
        draw.rectangle([bar_x1, bar_y1, bar_x1 + progress_width, bar_y2], fill=(45, 100, 180))


def create_scene_frame_at_time(scene, time_position, duration, layout=None):

    """
    Builds one complete video frame (or, when time_position >=
    duration, the "final" fully-written board used for the static
    gallery PNG) for a scene. Returns a PIL Image sized exactly
    VIDEO_WIDTH x VIDEO_HEIGHT. All text (title + bullets) is
    drawn strictly within the board's safe boundaries - see
    _draw_board_title and _draw_bullet_block_clipped.
    """

    if duration is None or duration <= 0:
        duration = 1.0
    else:
        duration = float(duration)

    if time_position is None:
        time_position = 0.0
    else:
        time_position = float(time_position)

    time_position = max(0.0, min(time_position, duration))

    theme = theme_for_scene(scene)

    camera = camera_for_scene(scene)

    transition_from_key = scene.get("camera_transition_from") if isinstance(scene, dict) else None

    transition_from_camera = CAMERA_BY_KEY.get(transition_from_key) if transition_from_key else None

    # --- content region: board background, title, bullets only ---

    content_image = Image.new("RGB", (VIDEO_WIDTH, CONTENT_HEIGHT))

    content_draw = ImageDraw.Draw(content_image)

    content_draw.rectangle(
        [0, 0, VIDEO_WIDTH - 1, CONTENT_HEIGHT - 1], fill=theme["background"]
    )

    content_draw.rectangle(
        [0, 0, VIDEO_WIDTH - 1, CONTENT_HEIGHT - 1], outline=theme["border"], width=3
    )

    content_draw.line([70, 100, VIDEO_WIDTH - 70, 100], fill=theme["divider"], width=3)

    _draw_board_title(content_draw, scene, theme)

    if layout is None:
        layout = build_scene_render_layout(draw=content_draw, scene=scene, duration=duration)

    if layout:
        _draw_bullet_text(content_draw, scene, theme, time_position, layout)

    content_image = apply_camera_transform(
        content_image,
        camera,
        transition_from=transition_from_camera,
        time_position=time_position,
        duration=duration,
    )

    # --- final frame: transformed content + fixed overlays ---

    final_image = Image.new("RGB", (VIDEO_WIDTH, VIDEO_HEIGHT))

    ImageDraw.Draw(final_image).rectangle(
        [0, 0, VIDEO_WIDTH - 1, VIDEO_HEIGHT - 1], fill=WHITE
    )

    final_image.paste(content_image, (0, 0))

    final_draw = ImageDraw.Draw(final_image)

    progress = time_position / duration

    _draw_footer(final_draw, scene)

    _draw_progress_bar(final_draw, progress)

    return final_image