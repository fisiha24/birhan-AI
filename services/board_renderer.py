# How long (in seconds) the simulated camera takes to ease from the
# previous board's framing into a new board's framing, at the start
# of the first scene of the new board. Clamped per-scene against
# that scene's own duration so a very short scene can never spend
# its whole runtime mid-transition.
CAMERA_TRANSITION_SECONDS = 1.4


def camera_for_scene(scene):

    key = scene.get("camera_angle") if isinstance(scene, dict) else None

    return CAMERA_BY_KEY.get(key, DEFAULT_CAMERA)


def _ease_in_out(progress):

    progress = max(0.0, min(1.0, progress))

    if progress < 0.5:
        return 4 * (progress ** 3)

    p = -2 * progress + 2

    return 1 - (p ** 3) / 2


def apply_camera_transform(image, camera, transition_from=None, time_position=0.0, duration=1.0):

    """
    Crops-and-zooms the CONTENT region to simulate `camera`'s
    framing. When `transition_from` (another camera dict) is
    given, the zoom/offset are eased from that camera's framing
    into `camera`'s framing over the first CAMERA_TRANSITION_SECONDS
    (clamped to this scene's own duration) of the clip, so the
    angle change is an actual, visible camera move instead of an
    instant, invisible swap.
    """

    target_zoom = camera.get("zoom", 1.0)
    target_offset_x = camera.get("offset_x", 0.5)
    target_offset_y = camera.get("offset_y", 0.5)

    if transition_from is not None:

        effective_transition_seconds = CAMERA_TRANSITION_SECONDS

        if duration and duration > 0:
            effective_transition_seconds = min(
                CAMERA_TRANSITION_SECONDS,
                max(0.3, duration * 0.6),
            )

        raw_progress = (
            time_position / effective_transition_seconds
            if effective_transition_seconds > 0
            else 1.0
        )

        progress = _ease_in_out(raw_progress)

        from_zoom = transition_from.get("zoom", 1.0)
        from_offset_x = transition_from.get("offset_x", 0.5)
        from_offset_y = transition_from.get("offset_y", 0.5)

        zoom = from_zoom + (target_zoom - from_zoom) * progress
        offset_x = from_offset_x + (target_offset_x - from_offset_x) * progress
        offset_y = from_offset_y + (target_offset_y - from_offset_y) * progress

    else:

        zoom = target_zoom
        offset_x = target_offset_x
        offset_y = target_offset_y

    if zoom <= 1.001:
        return image

    width, height = image.size

    crop_width = max(1, int(width / zoom))
    crop_height = max(1, int(height / zoom))

    max_x = max(0, width - crop_width)
    max_y = max(0, height - crop_height)

    left = int(max_x * offset_x)
    top = int(max_y * offset_y)

    cropped = image.crop((left, top, left + crop_width, top + crop_height))

    return cropped.resize((width, height), RESAMPLE_LANCZOS)


