"""
Birhan AI
Shared Board Rendering Engine

============================================================
WHY THIS FILE EXISTS
============================================================

services/video_generator.py (every video frame) and
services/visual_generator.py (the static per-scene gallery PNG
shown in lesson.html) both import from here and call the exact
same functions, so the gallery image and the video frame for a
given scene are generated by identical code.

============================================================
CHANGES IN THIS VERSION
============================================================

1. IMAGE GENERATION COMPLETELY REMOVED. The diagram panel (both
   the Pexels reference-photo lookup and the generated fallback
   icon) was producing inaccurate/unrelated images, so all of it
   - fetch_reference_image(), render_diagram_icon(),
   draw_diagram_panel(), the VISUAL_TYPE_IMAGE_QUERIES table, and
   every call site - has been removed. Every scene now renders as
   a pure text board: title + bullets only. Removing the diagram
   panel also frees up the board's horizontal writing width
   (BOARD_TEXT_MAX_WIDTH no longer reserves space for it), so
   text now has the full board width to work with.

2. TEXT BOUNDARY / CLIPPING FIX. All text (title + bullets) is
   now guaranteed to stay fully inside the visible board and
   video frame:
   - The title is measured and, if it would ever be wider than
     the safe horizontal area, its font is shrunk until it fits
     before being centered - it can never run past the left/right
     edges.
   - Bullet wrapping already respected BOARD_TEXT_MAX_WIDTH, but
     drawing is now also hard-clipped vertically: a bullet line is
     only drawn if it fits completely above BOARD_TEXT_BOTTOM_Y
     (the same boundary assign_visual_style() already plans
     against), so no line can ever bleed below the writable board
     area even in an edge-case rounding situation. A safe left/
     right margin is enforced on every line too.
   - assign_visual_style()'s board-splitting math is unchanged in
     behavior other than using the new, wider BOARD_TEXT_MAX_WIDTH.

============================================================
BOARD-WRITING MODEL (persistent, cross-scene board)
============================================================

assign_visual_style() walks the COMPLETE, final scene list once
and simulates a real notebook/whiteboard:

- A single fixed font size is used for the whole board (a real
  board doesn't resize its own handwriting scene to scene).
- Each scene's bullet points are measured against how much
  vertical room is left on the CURRENT board. If they fit, they
  are appended below whatever is already written; if they don't
  fit (and the board already has something on it), a brand new
  board is started - fresh theme, fresh camera angle, writing
  from the top again.
- Every scene remembers ("board_prior_bullets") the full text of
  everything earlier scenes already wrote on its board, so the
  video frame for ANY scene can redraw the whole board exactly as
  a viewer would have last seen it, then continue writing that
  scene's own new lines in sync with its narration. Nothing is
  ever erased just because a scene boundary passed.
- In the rare case a single scene's own notes are too long to
  fit even on a completely empty board, that one scene's font is
  shrunk just enough to fit (a real teacher writing smaller
  rather than starting a needless third board mid-thought).

============================================================
CAMERA (9 simulated framings, real visible motion)
============================================================

This is a static 2D PIL board, not a literal 3D camera, so each
preset crops-and-zooms the rendered CONTENT region (never the
footer/progress bar) to simulate a different framing. A new
board always gets a new camera angle, chosen from a fixed cycle
order picked specifically so consecutive angles differ sharply
in zoom and framing (never two similar-looking angles back to
back). Whenever a board's angle differs from the previous
board's, the first scene on the new board eases smoothly from
the old framing into the new one over the opening ~1.4s of the
clip, so the change is an actual, visible camera move.
"""

