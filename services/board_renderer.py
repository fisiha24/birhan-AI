def clean_text(text):

    if text is None:
        return ""

    text = str(text)
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    text = re.sub(r"([.!?]){2,}", r"\1", text)

    lines = []

    for line in text.split("\n"):
        line = re.sub(r"[ \t]+", " ", line).strip()
        if line:
            lines.append(_ensure_terminal_punctuation(line))

    return "\n".join(lines)


def _ensure_terminal_punctuation(line):

    stripped = line.strip()

    if not stripped:
        return stripped

    if stripped[-1] in ".!?:)\u201d\"'":
        return stripped

    if len(stripped.split()) <= 3:
        return stripped

    return stripped + "."


def get_text_width(draw, text, font):

    if not text:
        return 0

    bbox = draw.textbbox((0, 0), text, font=font)

    return bbox[2] - bbox[0]


def wrap_text(draw, text, font, max_width):

    text = text.strip()

    if not text:
        return []

    words = text.split()

    lines = []
    current_line = ""

    for word in words:

        test_line = (current_line + " " + word).strip()

        if get_text_width(draw, test_line, font) <= max_width:
            current_line = test_line
        else:
            if current_line:
                lines.append(current_line)
            current_line = word

    if current_line:
        lines.append(current_line)

    return lines


def get_scene_text(scene):

    if not isinstance(scene, dict):
        return ""

    text = (
        scene.get("board_text", "")
        or scene.get("narration", "")
        or scene.get("text", "")
        or scene.get("explanation", "")
        or scene.get("content", "")
        or scene.get("description", "")
        or scene.get("title", "")
    )

    return clean_text(text)


def get_scene_title(scene):

    if not isinstance(scene, dict):
        return ""

    return clean_text(scene.get("title", ""))


