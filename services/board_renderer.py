def split_into_bullet_points(text):

    text = clean_text(text)

    if not text:
        return []

    bullet_points = []
    seen_normalized = set()

    for raw_line in text.split("\n"):

        line = raw_line.strip()

        if not line:
            continue

        line = re.sub(r"^[•●▪◦▸★❖►✧◆*\-–—]\s*", "", line).strip()

        if not line:
            continue

        numbered_parts = re.split(
            r"(?<=[.!?])\s+(?=(?:\d+[\.)]|[A-Z][\.)]))", line
        )

        parts_to_process = numbered_parts if len(numbered_parts) > 1 else re.split(
            r"(?<=[.!?])\s+", line
        )

        for part in parts_to_process:

            part = part.strip()

            if not part:
                continue

            normalized = re.sub(r"\s+", " ", part.lower())

            if normalized in seen_normalized:
                continue

            seen_normalized.add(normalized)
            bullet_points.append(part)

    return bullet_points


def pick_bullet_color(theme, text):

    palette = PALETTES.get(theme.get("palette", "deep"), PALETTES["deep"])

    lowered = text.lower()

    looks_like_formula = bool(re.search(r"[=+\-*/^]", text)) and any(
        character.isdigit() for character in text
    )

    looks_like_definition = (
        ":" in text or " si unit" in lowered or lowered.startswith("definition")
    )

    looks_like_example = (
        lowered.startswith("example")
        or lowered.startswith("e.g.")
        or " e.g." in lowered
        or lowered.startswith("for example")
    )

    looks_like_key_term = (
        len(text.split()) <= 3 and not looks_like_formula and not looks_like_definition
    )

    if looks_like_formula:
        return palette["formula"]

    if looks_like_definition:
        return palette["definition"]

    if looks_like_example:
        return palette["example"]

    if looks_like_key_term:
        return palette["key_term"]

    return palette["note"]


def draw_marker(draw, x, y, size, color, shape):

    if shape == "circle":
        draw.ellipse([x, y, x + size, y + size], fill=color)

    elif shape == "square":
        draw.rectangle([x, y, x + size, y + size], fill=color)

    elif shape == "square_ring":
        draw.rectangle([x, y, x + size, y + size], outline=color, width=3)

    elif shape == "diamond":
        mid = size / 2
        draw.polygon(
            [(x + mid, y), (x + size, y + mid), (x + mid, y + size), (x, y + mid)],
            fill=color,
        )

    elif shape == "star":
        cx, cy, r = x + size / 2, y + size / 2, size / 2
        points = []
        for i in range(5):
            angle = -1.5707963 + i * (2 * 3.14159265 / 5)
            points.append((cx + r * _cos(angle), cy + r * _sin(angle)))
            angle_inner = angle + (3.14159265 / 5)
            points.append((cx + (r / 2.3) * _cos(angle_inner), cy + (r / 2.3) * _sin(angle_inner)))
        draw.polygon(points, fill=color)

    elif shape == "triangle":
        draw.polygon(
            [(x + size / 2, y), (x + size, y + size), (x, y + size)],
            fill=color,
        )

    elif shape == "ring":
        draw.ellipse([x, y, x + size, y + size], outline=color, width=3)

    elif shape == "cross":
        third = size / 3
        draw.rectangle([x + third, y, x + 2 * third, y + size], fill=color)
        draw.rectangle([x, y + third, x + size, y + 2 * third], fill=color)

    elif shape == "arrow":
        mid = size / 2
        draw.polygon(
            [(x, y + mid - 3), (x + size * 0.6, y + mid - 3), (x + size * 0.6, y),
             (x + size, y + mid), (x + size * 0.6, y + size), (x + size * 0.6, y + mid + 3),
             (x, y + mid + 3)],
            fill=color,
        )

    else:  # "dash"
        draw.rectangle([x, y + size * 0.35, x + size, y + size * 0.65], fill=color)


def _cos(angle):
    import math
    return math.cos(angle)


def _sin(angle):
    import math
    return math.sin(angle)


