def _normalize_word(word):

    return re.sub(r"[^\w']+", "", str(word or "")).lower()


def _tokenize_words(text):

    if not text:
        return []

    return [word for word in re.split(r"\s+", text.strip()) if word]


def align_words_to_speech(board_words, speech_boundaries, lookahead=20):

    normalized_speech = [_normalize_word(b.get("text", "")) for b in speech_boundaries]

    total_speech_words = len(speech_boundaries)

    pointer = 0

    aligned = []

    for word in board_words:

        target = _normalize_word(word)

        found_index = None

        if target:

            window_end = min(total_speech_words, pointer + lookahead)

            for index in range(pointer, window_end):
                if normalized_speech[index] == target:
                    found_index = index
                    break

            if found_index is None:
                for index in range(pointer, total_speech_words):
                    if normalized_speech[index] == target:
                        found_index = index
                        break

        if found_index is not None:

            boundary = speech_boundaries[found_index]

            aligned.append({"start": boundary["start"], "end": boundary["end"], "matched": True})

            pointer = found_index + 1

        else:

            aligned.append({"start": None, "end": None, "matched": False})

    return aligned


def _fill_unmatched_word_times(aligned, duration):

    total_words = len(aligned)

    if total_words == 0:
        return aligned

    matched_indices = [i for i, e in enumerate(aligned) if e["matched"]]

    if not matched_indices:

        for index in range(total_words):
            time_value = duration * (index + 1) / (total_words + 1)
            aligned[index]["start"] = time_value
            aligned[index]["end"] = time_value

        return aligned

    first_matched = matched_indices[0]
    first_start = aligned[first_matched]["start"]

    if first_matched > 0:
        for index in range(first_matched):
            fraction = (index + 1) / (first_matched + 1)
            time_value = first_start * fraction
            aligned[index]["start"] = time_value
            aligned[index]["end"] = time_value

    for position in range(len(matched_indices) - 1):

        left_index = matched_indices[position]
        right_index = matched_indices[position + 1]

        gap_size = right_index - left_index - 1

        if gap_size <= 0:
            continue

        left_end = aligned[left_index]["end"]
        right_start = aligned[right_index]["start"]
        gap_duration = max(right_start - left_end, 0.0)

        for offset in range(1, gap_size + 1):
            time_value = left_end + (gap_duration * offset / (gap_size + 1))
            aligned[left_index + offset]["start"] = time_value
            aligned[left_index + offset]["end"] = time_value

    last_matched = matched_indices[-1]
    last_end = aligned[last_matched]["end"]

    if last_matched < total_words - 1:
        remaining = total_words - 1 - last_matched
        for offset in range(1, remaining + 1):
            time_value = last_end + ((duration - last_end) * offset / (remaining + 1))
            aligned[last_matched + offset]["start"] = time_value
            aligned[last_matched + offset]["end"] = time_value

    return aligned


def build_bullet_word_timelines(bullet_points, duration, word_boundaries=None):

    if duration <= 0:
        duration = 1.0

    board_words = []
    bullet_word_ranges = []

    for bullet_text in bullet_points:

        words = _tokenize_words(bullet_text)
        start_index = len(board_words)
        board_words.extend(words)
        bullet_word_ranges.append((start_index, len(board_words)))

    speech_boundaries = []

    if word_boundaries:

        for boundary in word_boundaries:

            if not isinstance(boundary, dict):
                continue

            try:
                start_time = float(boundary.get("start"))
            except (TypeError, ValueError):
                continue

            try:
                end_time = float(boundary.get("end", start_time))
            except (TypeError, ValueError):
                end_time = start_time

            start_time = max(0.0, min(start_time, duration))
            end_time = max(start_time, min(end_time, duration))

            speech_boundaries.append(
                {"text": boundary.get("text", ""), "start": start_time, "end": end_time}
            )

        speech_boundaries.sort(key=lambda item: item["start"])

    aligned = align_words_to_speech(board_words, speech_boundaries)

    suppressed_indices = set()

    if speech_boundaries:

        for start_index, end_index in bullet_word_ranges:

            bullet_has_match = any(
                aligned[index]["matched"] for index in range(start_index, end_index)
            )

            if not bullet_has_match:
                for index in range(start_index, end_index):
                    suppressed_indices.add(index)

    aligned = _fill_unmatched_word_times(aligned, duration)

    for index in suppressed_indices:
        aligned[index]["start"] = None
        aligned[index]["end"] = None

    timelines = []

    for bullet_text, (start_index, end_index) in zip(bullet_points, bullet_word_ranges):

        words = board_words[start_index:end_index]

        word_starts = [aligned[index]["start"] for index in range(start_index, end_index)]

        timelines.append({"words": words, "word_starts": word_starts})

    return timelines


def get_visible_word_count(word_starts, time_position):

    visible_count = 0

    for start_time in word_starts:
        if start_time is not None and start_time <= time_position:
            visible_count += 1
        else:
            break

    return visible_count


# ============================================================
# PERSISTENT, CROSS-SCENE BOARD ASSIGNMENT
#
# Walks the COMPLETE, final scene list once and simulates a real
# writing board: each scene's bullets are appended below whatever
# is already written on the CURRENT board, using ONE fixed font
# size for the whole board. A new board (fresh theme, fresh
# camera, writing restarts from the top) is only started once the
# current board genuinely has no room left for the next scene's
# notes. Every scene is tagged with "board_prior_bullets" - the
# full text of everything already written on its board by earlier
# scenes - so the frame for any scene can redraw the whole board
# exactly as a viewer would have last seen it before continuing
# to write that scene's own new lines.
# ============================================================

def _bullet_block_height(draw, bullet_text, font, max_width, line_height, gap):

    lines = wrap_text(draw, bullet_text, font, max_width - 55)

    if not lines:
        return 0

    return len(lines) * line_height + gap


def _measure_bullets_height(draw, bullet_points, font, max_width, line_height, gap):

    total = 0.0

    for bullet_text in bullet_points:
        total += _bullet_block_height(draw, bullet_text, font, max_width, line_height, gap)

    return total


def _shrink_font_to_fit(draw, bullet_points, max_width, max_height):

    """
    Fallback for the rare case where a single scene's own notes
    are too long to fit even on a completely empty board at the
    standard board font size. Shrinks the font just for this one
    scene until its notes fit (or, failing that, until the
    minimum readable size is reached).
    """

    for size in range(BOARD_TEXT_FONT_SIZE, BOARD_TEXT_MIN_FONT_SIZE - 1, -2):

        font = load_font(size, bold=False)
        line_height = int(size * 1.45)
        gap = int(size * 0.65)

        total = _measure_bullets_height(draw, bullet_points, font, max_width, line_height, gap)

        if total <= max_height:
            return size, line_height, gap, total

    size = BOARD_TEXT_MIN_FONT_SIZE
    font = load_font(size, bold=False)
    line_height = int(size * 1.45)
    gap = int(size * 0.65)

    total = _measure_bullets_height(draw, bullet_points, font, max_width, line_height, gap)

    return size, line_height, gap, total


def assign_visual_style(scenes):

    """
    Mutates each scene dict in place, setting "board_theme",
    "camera_angle", "board_font_size", "board_prior_bullets", and
    (on the first scene of a new board whose camera differs from
    the previous board's) "camera_transition_from". Call this
    ONCE, on the COMPLETE final scene list (including any
    assessment/closing scenes appended after
    services/lesson_parser.py runs), before generating any scene
    images or video frames.
    """

    if not isinstance(scenes, list):
        return scenes

    probe_image = Image.new("RGB", (VIDEO_WIDTH, CONTENT_HEIGHT))
    ImageDraw.Draw(probe_image).rectangle(
        [0, 0, VIDEO_WIDTH - 1, CONTENT_HEIGHT - 1], fill=WHITE
    )
    probe_draw = ImageDraw.Draw(probe_image)

    default_font = load_font(BOARD_TEXT_FONT_SIZE, bold=False)
    default_line_height = int(BOARD_TEXT_FONT_SIZE * 1.45)
    default_gap = int(BOARD_TEXT_FONT_SIZE * 0.65)

    theme_pointer = 0
    camera_pointer = 0

    used_height = 0.0
    board_prior_bullets = []

    current_theme_key = None
    current_camera_key = None
    previous_camera_key = None

    def start_new_board():

        nonlocal used_height, board_prior_bullets
        nonlocal current_theme_key, current_camera_key, previous_camera_key
        nonlocal theme_pointer, camera_pointer

        previous_camera_key = current_camera_key

        current_theme_key = BOARD_THEMES[theme_pointer % len(BOARD_THEMES)]["key"]
        theme_pointer += 1

        current_camera_key = CAMERA_CYCLE_ORDER[camera_pointer % len(CAMERA_CYCLE_ORDER)]
        camera_pointer += 1

        used_height = 0.0
        board_prior_bullets = []

    for scene in scenes:

        if not isinstance(scene, dict):
            continue

        scene_text = get_scene_text(scene)
        bullet_points = split_into_bullet_points(scene_text) if scene_text else []

        is_new_board_start = False

        if current_theme_key is None:
            start_new_board()
            is_new_board_start = True

        font_size = BOARD_TEXT_FONT_SIZE
        line_height = default_line_height
        gap = default_gap

        required_height = _measure_bullets_height(
            probe_draw, bullet_points, default_font, BOARD_TEXT_MAX_WIDTH, line_height, gap
        )

        if bullet_points and used_height > 0 and used_height + required_height > BOARD_TEXT_MAX_HEIGHT:

            # No room left on the current board for this scene's
            # notes - start a fresh board, writing from the top.
            start_new_board()
            is_new_board_start = True

            required_height = _measure_bullets_height(
                probe_draw, bullet_points, default_font, BOARD_TEXT_MAX_WIDTH, line_height, gap
            )

        if bullet_points and used_height == 0 and required_height > BOARD_TEXT_MAX_HEIGHT:

            # Even a brand new, empty board can't fit this one
            # scene's notes at the standard size - shrink just
            # this scene's font rather than leaving a needless
            # extra board split mid-thought.
            font_size, line_height, gap, required_height = _shrink_font_to_fit(
                probe_draw, bullet_points, BOARD_TEXT_MAX_WIDTH, BOARD_TEXT_MAX_HEIGHT
            )

        scene["board_theme"] = current_theme_key
        scene["camera_angle"] = current_camera_key
        scene["board_font_size"] = font_size
        scene["board_prior_bullets"] = list(board_prior_bullets)

        if (
            is_new_board_start
            and previous_camera_key is not None
            and previous_camera_key != current_camera_key
        ):
            scene["camera_transition_from"] = previous_camera_key
        else:
            scene.pop("camera_transition_from", None)

        board_prior_bullets.extend(bullet_points)
        used_height += required_height

    return scenes


